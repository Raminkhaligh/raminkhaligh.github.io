#!/usr/bin/env python3
"""
Auto-generate blog/posts.json and the static blog card blocks for
Ramin Khaligh's portfolio site.

Scans all .html files under blog/ and extracts:
 - title from <title>
 - summary from <meta name="description">
 - og:image or default image
 - date/lastmod from each post's own article:published_time /
   article:modified_time meta tags, falling back to git log only if a
   post doesn't have them (git history is a poor proxy for editorial
   publish date — e.g. it goes wrong entirely after a history rewrite
   or a squashed/consolidated commit)
 - auto-detect thumbnail from blog/images/

Outputs:
 1. blog/posts.json sorted by most recent date.
 2. Server-rendered card blocks between "blog-cards" marker comments in
    index.html (EN home, 3 newest), fa/index.html (Persian-first, 3), and
    blog/index.html (full list), plus the static ItemList JSON-LD on the
    blog hub.  Crawlers that don't execute JS get real internal links;
    the client-side loaders replace these blocks at runtime, so
    posts.json stays the single source of truth.
"""

import html as html_mod
import json
import re
import subprocess
from datetime import date
from pathlib import Path

ROOT = Path(__file__).parent
BLOG_DIR = ROOT / "blog"
IMG_DIR = BLOG_DIR / "images"
OUTPUT_FILE = BLOG_DIR / "posts.json"
DEFAULT_IMAGE = "/assets/og-cover.webp"
SITE_ORIGIN = "https://raminkhaligh.ir"

CARDS_START = "<!-- blog-cards:start (auto-generated by generate_posts_json.py - do not edit) -->"
CARDS_END = "<!-- blog-cards:end -->"
ITEMLIST_START = "<!-- blog-itemlist:start (auto-generated by generate_posts_json.py - do not edit) -->"
ITEMLIST_END = "<!-- blog-itemlist:end -->"

FA_RANGE = re.compile(r"[\u0600-\u06FF]")
MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun",
          "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]


def get_last_commit_date(path):
    try:
        result = subprocess.check_output(
            ["git", "log", "-1", "--format=%ci", str(path)],
            stderr=subprocess.DEVNULL
        )
        return result.decode().strip().split(" ")[0]
    except Exception:
        return date.today().isoformat()


def extract_meta(html):
    title = re.search(r"<title>(.*?)</title>", html, re.I | re.S)
    desc = re.search(r'<meta[^>]+name=["\']description["\'][^>]+content=["\'](.*?)["\']', html, re.I)
    image = re.search(r'<meta[^>]+property=["\']og:image["\'][^>]+content=["\'](.*?)["\']', html, re.I)
    published = re.search(r'<meta[^>]+property=["\']article:published_time["\'][^>]+content=["\'](.*?)["\']', html, re.I)
    modified = re.search(r'<meta[^>]+property=["\']article:modified_time["\'][^>]+content=["\'](.*?)["\']', html, re.I)
    raw_title = title.group(1).strip() if title else "Untitled"
    # <title> is "Post Title | Site Name" for SEO; strip the site-name suffix
    # so cards/alt text show just the post title, not the full SEO string.
    display_title = raw_title.split("|")[0].strip() if "|" in raw_title else raw_title
    # og:image must be absolute (required by the OG spec for crawlers), but
    # the card/thumbnail render on-page from this same value, so keep it
    # root-relative here — otherwise local/staging previews try to hotlink
    # the live production asset instead of the file being edited.
    img = image.group(1).strip() if image else None
    if img and img.startswith(SITE_ORIGIN):
        img = img[len(SITE_ORIGIN):]
    return {
        "title": display_title,
        "summary": desc.group(1).strip() if desc else "",
        "image": img,
        "published": published.group(1).strip()[:10] if published else None,
        "modified": modified.group(1).strip()[:10] if modified else None,
    }


def detect_thumbnail(html_file):
    base_name = html_file.stem
    for ext in ["jpg", "jpeg", "png", "webp"]:
        candidate = IMG_DIR / f"{base_name}.{ext}"
        if candidate.exists():
            return f"blog/images/{candidate.name}"
    return DEFAULT_IMAGE


def esc(text):
    return html_mod.escape(text or "", quote=True)


def us_date(iso):
    try:
        y, m, d = (int(x) for x in iso.split("-"))
        return f"{MONTHS[m - 1]} {d}, {y}"
    except (ValueError, IndexError, AttributeError):
        return iso


def is_fa(post):
    return bool(FA_RANGE.search(post.get("title") or ""))


def card_home_en(post):
    return f'''        <article class="card blog-card">
          <a class="blog-card__link" href="/{post["url"]}">
            <div class="blog-card__media">
              <img class="blog-card__img" src="{esc(post["image"])}" alt="{esc(post["title"])}" loading="lazy" decoding="async" width="800" height="450" />
            </div>
            <div class="blog-card__body">
              <h3 class="blog-card__title">{esc(post["title"])}</h3>
              <p class="blog-card__excerpt">{esc(post["summary"])}</p>
              <span class="blog-card__cta">Read Article &rarr;</span>
            </div>
          </a>
        </article>'''


def card_home_fa(post):
    return f'''        <article class="card blog-card">
          <a class="blog-card__link" href="/{post["url"]}">
            <div class="blog-card__media">
              <img class="blog-card__img" src="{esc(post["image"])}" alt="{esc(post["title"])}" loading="lazy" decoding="async" width="800" height="450" />
            </div>
            <div class="blog-card__body">
              <h3 class="blog-card__title">{esc(post["title"])}</h3>
              <p class="blog-card__excerpt">{esc(post["summary"])}</p>
              <span class="blog-card__cta">مطالعه مقاله &larr;</span>
            </div>
          </a>
        </article>'''


def card_hub(post):
    url = f"/{post['url']}"
    return f'''        <article class="card blog-card">
          <a class="blog-card__link" href="{url}">
            <div class="blog-card__media">
              <img class="blog-card__img" src="{esc(post["image"])}" alt="{esc(post["title"])}" loading="lazy" decoding="async" width="1200" height="675" />
            </div>
            <div class="blog-card__body">
              <h3 class="blog-card__title">{esc(post["title"])}</h3>
              <p class="blog-card__excerpt">{esc(post["summary"])}</p>
            </div>
          </a>
          <div class="blog-card__footer">
            <a href="{url}" class="btn">Read More →</a>
            <small class="blog-card__date">{us_date(post["date"])}</small>
          </div>
        </article>'''


def replace_between(path, start, end, content, fallback_insert=None):
    """Replace the text between marker comments; insert fresh markers (with
    fallback_insert content) when a file predates the marker system."""
    html = path.read_text(encoding="utf-8")
    pat = re.compile(re.escape(start) + r"\n.*?\n" + re.escape(end), re.S)
    block = f"{start}\n{content}\n{end}"
    if pat.search(html):
        html = pat.sub(lambda _: block, html, count=1)
    elif fallback_insert is not None:
        html = html.replace(fallback_insert, block + "\n" + fallback_insert, 1)
    else:
        print(f"  WARNING: markers not found in {path.name} — skipped")
        return False
    path.write_text(html, encoding="utf-8", newline="")
    return True


def render_static_blocks(posts):
    # EN home: featured first, then newest (mirrors the runtime loader), 3 cards
    featured = [p for p in posts if p.get("featured")]
    latest = [p for p in posts if not p.get("featured")]
    en_cards = "\n\n".join(card_home_en(p) for p in (featured + latest)[:3])
    ok1 = replace_between(ROOT / "index.html", CARDS_START, CARDS_END, en_cards)

    # FA home: Persian posts first (mirrors the runtime loader), then newest
    fa_sorted = sorted(posts, key=lambda p: (is_fa(p), p["date"]), reverse=True)
    fa_cards = "\n\n".join(card_home_fa(p) for p in fa_sorted[:3])
    ok2 = replace_between(ROOT / "fa" / "index.html", CARDS_START, CARDS_END, fa_cards)

    # Blog hub: full list + static ItemList JSON-LD
    hub_cards = "\n\n".join(card_hub(p) for p in posts)
    ok3 = replace_between(BLOG_DIR / "index.html", CARDS_START, CARDS_END, hub_cards)

    # JSON-LD strings need JSON escaping, not HTML escaping — build with
    # json.dumps so titles containing quotes/& stay literal.
    items = ",\n".join(
        json.dumps({
            "@type": "ListItem",
            "position": i + 1,
            "url": f"{SITE_ORIGIN}/{p['url']}",
            "name": p["title"],
        }, ensure_ascii=False)
        for i, p in enumerate(posts))
    itemlist = (
        "  <script type=\"application/ld+json\" id=\"itemlist-jsonld\">\n"
        "  {\n"
        "    \"@context\": \"https://schema.org\",\n"
        "    \"@type\": \"ItemList\",\n"
        "    \"itemListElement\": [\n"
        f"{items}\n"
        "    ]\n"
        "  }\n"
        "  </script>")
    ok4 = replace_between(BLOG_DIR / "index.html", ITEMLIST_START, ITEMLIST_END, itemlist)

    print(f"Static blocks updated: en-home={ok1} fa-home={ok2} hub-cards={ok3} hub-itemlist={ok4}")


def main():
    posts = []
    for html_file in BLOG_DIR.glob("*.html"):
        if html_file.name == "index.html":
            continue

        html = html_file.read_text(encoding="utf-8", errors="ignore")
        meta = extract_meta(html)
        fallback_date = get_last_commit_date(html_file)
        date_value = meta["published"] or fallback_date
        lastmod = meta["modified"] or date_value
        image = meta["image"] or detect_thumbnail(html_file)

        posts.append({
            "title": meta["title"],
            "summary": meta["summary"],
            "date": date_value,
            "lastmod": lastmod,
            "url": f"blog/{html_file.name}",
            "image": image,
            "featured": False
        })

    posts.sort(key=lambda x: x["date"], reverse=True)
    OUTPUT_FILE.write_text(json.dumps(posts, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Generated {OUTPUT_FILE} with {len(posts)} posts.")
    render_static_blocks(posts)


if __name__ == "__main__":
    main()
